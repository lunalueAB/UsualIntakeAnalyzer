    /// 시드의 FoodNames는 코드집의 FoodGroup(또는 FoodName) 라벨이며,
    /// 코드집이 등록되면 ExpandCodesFromCodebook() 으로 실제 1차코드 집합이 채워진다.
    /// </summary>
