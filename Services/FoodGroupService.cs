        // 시드 버전 — 시드 데이터(식품군DB.xlsx 기반)가 바뀌면 ↑.
        // 기존 사용자의 식품군 파일이 이전 버전이면 IsBuiltIn 항목을 새 시드로 교체.
        private const int CurrentSeedVersion = 2;

        private static string _file = "";
        private static string _versionFile = "";

        public static void Initialize(string root)
        {
            _file        = Path.Combine(root, "food_groups.json");
            _versionFile = Path.Combine(root, "food_groups_version.txt");

            int existingVersion = 0;
            if (File.Exists(_versionFile))
                int.TryParse(File.ReadAllText(_versionFile).Trim(), out existingVersion);

            if (!File.Exists(_file))
            {
                // 최초 실행: 새 시드 그대로 저장
                SaveAll(GetSeedBuiltins());
                File.WriteAllText(_versionFile, CurrentSeedVersion.ToString());
            }
            else if (existingVersion < CurrentSeedVersion)
            {
                // 시드 버전 업그레이드: 사용자 정의는 보존하고 IsBuiltIn 만 교체
                ReSeedBuiltinsPreservingUser();
                File.WriteAllText(_versionFile, CurrentSeedVersion.ToString());
            }

            // 코드집이 이미 있으면 시드의 FoodCodes 자동 확장
            if (AppDataService.CodebookExists()) ExpandCodesFromCodebook();
        }

        private static void ReSeedBuiltinsPreservingUser()
        {
            var userDefined = LoadAll().Where(g => !g.IsBuiltIn).ToList();
            var combined = new List<FoodGroup>();
            combined.AddRange(GetSeedBuiltins());
            combined.AddRange(userDefined);
            SaveAll(combined);
        }

        public static List<FoodGroup> LoadAll()
        {
            if (!File.Exists(_file)) return new List<FoodGroup>();
            try
            {
                return JsonConvert.DeserializeObject<List<FoodGroup>>(
                    File.ReadAllText(_file)) ?? new List<FoodGroup>();
            }
            catch { return new List<FoodGroup>(); }
        }

        public static void SaveAll(List<FoodGroup> list)
            => File.WriteAllText(_file,
                                 JsonConvert.SerializeObject(list, Formatting.Indented));

        public static FoodGroup Add(FoodGroup g)
        {
            var list = LoadAll();
            g.CreatedAt = g.UpdatedAt = DateTime.Now;
            list.Add(g);
            SaveAll(list);
            return g;
        }

        public static void Update(FoodGroup g)
        {
            var list = LoadAll();
            var idx = list.FindIndex(x => x.Id == g.Id);
            if (idx < 0) return;
            g.UpdatedAt = DateTime.Now;
            list[idx]   = g;
            SaveAll(list);
        }

        public static void Delete(string id)
        {
            var list = LoadAll();
            list.RemoveAll(x => x.Id == id);
            SaveAll(list);
        }

        public static FoodGroup? Get(string id)
            => LoadAll().FirstOrDefault(x => x.Id == id);

        // ── 코드집 매칭으로 FoodCodes 자동 확장 ─────────────────────────
        /// <summary>
        /// 모든 시드(IsBuiltIn=true) 식품군에 대해 코드집을 스캔하여
        /// FoodNames(=식품군 라벨)와 일치하는 코드집 행의 Code를 모아
        /// FoodCodes를 채운다. 사용자가 직접 만든 식품군은 건드리지 않는다.
        /// </summary>
        public static void ExpandCodesFromCodebook()
        {
            if (!AppDataService.CodebookExists()) return;
            List<FoodCodeEntry> codebook;
            try
            {
                codebook = ExcelParserService.ParseCodebook(AppDataService.GetCodebookPath());
            }
            catch { return; }

            var list = LoadAll();
            bool changed = false;
            foreach (var g in list)
            {
                if (!g.IsBuiltIn) continue;          // 사용자 정의는 보존
                var labels = new HashSet<string>(g.FoodNames, StringComparer.Ordinal);
                if (labels.Count == 0) continue;

                // 코드집 항목 중 FoodGroup 또는 FoodName이 시드 라벨에 매칭되는 것
                var matched = codebook
                    .Where(e =>
                        (!string.IsNullOrEmpty(e.FoodGroup) && labels.Contains(e.FoodGroup.Trim()))
                        || (!string.IsNullOrEmpty(e.FoodName)  && labels.Contains(e.FoodName.Trim())))
                    .ToList();

                var newCodes = matched.Select(e => e.Code)
                                       .Where(c => !string.IsNullOrWhiteSpace(c))
                                       .Distinct()
                                       .OrderBy(c => c)
                                       .ToList();
                var newNames = matched.Select(e => e.FoodName)
                                       .Where(n => !string.IsNullOrWhiteSpace(n))
                                       .Distinct()
                                       .OrderBy(n => n)
                                       .ToList();

                // 라벨 정보(FoodNames) 자체는 유지하되, 매칭된 식품명을 함께 보강
                if (!newCodes.SequenceEqual(g.FoodCodes))
                {
                    g.FoodCodes = newCodes;
                    changed = true;
                }
                // 표시용 식품명도 코드집에서 보강 (라벨이 그룹명일 경우 실제 식품명 누적)
                var union = new HashSet<string>(g.FoodNames);
                int before = union.Count;
                foreach (var n in newNames) union.Add(n);
                if (union.Count != before)
                {
                    g.FoodNames = union.OrderBy(x => x).ToList();
                    changed = true;
                }
            }
            if (changed) SaveAll(list);
        }

